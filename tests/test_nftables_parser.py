SAMPLE_NFTABLES_TEXT = """
table ip filter {
    chain input {
        type filter hook input priority filter; policy accept;
        tcp dport 22 accept
    }
}

table ip nat {
    chain prerouting {
        type nat hook prerouting priority dstnat; policy accept;
        # Direct TCP DNAT with handle
        tcp dport 8443 dnat to 10.88.1.2:8443 # handle 10
        # Direct UDP DNAT with handle
        udp dport 2083 dnat to 10.88.1.2:2083 # handle 11
        # Combined protocol DNAT
        meta l4proto { tcp, udp } th dport 9090 dnat to 10.88.1.2:9090 # handle 12
        # Multiple ports set
        tcp dport { 8080, 8081 } dnat to 10.0.0.5 # handle 13
        # Omitted target port (falls back to inbound port)
        tcp dport 7777 dnat to 10.0.0.9 # handle 14
    }
}

table ip6 nat {
    chain prerouting {
        type nat hook prerouting priority dstnat; policy accept;
        # IPv6 target
        tcp dport 9443 dnat to [2001:db8::1]:9443 # handle 20
    }
}

# Should be completely ignored because it is managed by XForwarder
table ip xfwd_orchestrator {
    chain prerouting {
        type nat hook prerouting priority dstnat; policy accept;
        tcp dport 443 dnat to 10.88.1.2:443 # handle 99
    }
}
"""

