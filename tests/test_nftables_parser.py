    def test_import_nftables_rules_into_config_file(self):
        initial_cfg = {
            "wan_interface": "eth0",
            "rules": [
                {
                    "id": "rule-443",
                    "port": 443,
                    "destinations": [{"priority": 1, "type": "haproxy", "target": "2001:db8::1", "port": 443}]
                }
            ]
        }

        mock_discovered = [
            {
                "id": "rule-8443",
                "port": 8443,
                "protocol": "both",
                "active_priority": 2,
                "force_override": 0,
                "destinations": [
                    {"priority": 1, "type": "nginx", "target": "10.88.1.2", "port": 8443, "proxy_protocol": False, "comment": ""},
                    {"priority": 2, "type": "nftables", "target": "10.88.1.2", "port": 8443, "proxy_protocol": False, "comment": ""}
                ],
                "_meta": {"handle": 10, "family": "ip", "table": "nat", "chain": "prerouting"}
            }
        ]

        with tempfile.NamedTemporaryFile("w+", delete=False, suffix=".json") as f:
            json.dump(initial_cfg, f)
            cfg_path = f.name

        try:
            with patch("core.nftables_parser.discover_importable_nftables_rules", return_value=mock_discovered), \
                 patch("core.nftables_parser.backup_legacy_nftables", return_value="/tmp/test_backup.nft"), \
                 patch("core.nftables_parser.deactivate_legacy_rules", return_value=(1, ["Deactivated handle 10"])):
                count, ports, logs = import_nftables_rules_into_config(cfg_path, deactivate_legacy=True)
                self.assertEqual(count, 1)
                self.assertEqual(ports, [8443])

                with open(cfg_path, "r", encoding="utf-8") as f:
                    updated = json.load(f)

                rule_ports = [r["port"] for r in updated["rules"]]
                self.assertIn(443, rule_ports)
                self.assertIn(8443, rule_ports)

                # Ensure private _meta was cleaned before saving
                r_new = next(r for r in updated["rules"] if r["port"] == 8443)
                self.assertNotIn("_meta", r_new)
        finally:
            if os.path.exists(cfg_path):
                os.remove(cfg_path)

    def test_deactivate_legacy_rules(self):
        rules = [
            {
                "port": 8443,
                "_meta": {"family": "ip", "table": "nat", "chain": "prerouting", "handle": 77}
            }
        ]
        with patch("shutil.which", return_value="/usr/sbin/nft"), \
             patch("subprocess.run") as mock_sub:
            mock_sub.return_value = MagicMock(returncode=0, stdout="", stderr="")
            deact, logs = deactivate_legacy_rules(rules)
            self.assertEqual(deact, 1)
            mock_sub.assert_called_with(
                ["nft", "delete", "rule", "ip", "nat", "prerouting", "handle", "77"],
                capture_output=True, text=True, timeout=2.0
            )

