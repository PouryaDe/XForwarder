SAMPLE_IPTABLES_TEXT = """
# Generated by iptables-save
*nat
:PREROUTING ACCEPT [0:0]
:INPUT ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A PREROUTING -p tcp -m tcp --dport 5001 -j DNAT --to-destination 10.88.1.2:5001
-A PREROUTING -p udp -m udp --dport 5002 -j DNAT --to-destination 10.88.1.2:5002
COMMIT
"""


class TestNFTablesParser(unittest.TestCase):

    def test_parse_nftables_text(self):
        rules = parse_nftables_text(SAMPLE_NFTABLES_TEXT)
        self.assertTrue(len(rules) >= 6)

        ports = {r["port"] for r in rules}
        self.assertIn(8443, ports)
        self.assertIn(2083, ports)
        self.assertIn(9090, ports)
        self.assertIn(8080, ports)
        self.assertIn(8081, ports)
        self.assertIn(7777, ports)
        self.assertIn(9443, ports)
        # Port 443 in xfwd_orchestrator must be skipped
        self.assertNotIn(443, ports)

        r_8443 = next(r for r in rules if r["port"] == 8443)
        self.assertEqual(r_8443["protocol"], "tcp")
        self.assertEqual(r_8443["active_priority"], 2)
        dests = r_8443["destinations"]
        self.assertEqual(len(dests), 2)
        self.assertEqual(dests[1]["type"], "nftables")
        self.assertEqual(dests[1]["target"], "10.88.1.2")
        self.assertEqual(dests[1]["port"], 8443)
        self.assertEqual(r_8443["_meta"]["handle"], 10)

        # Port 7777 had omitted target port; check fallback
        r_7777 = next(r for r in rules if r["port"] == 7777)
        self.assertEqual(r_7777["destinations"][1]["port"], 7777)

        # Port 9443 had IPv6 target
        r_9443 = next(r for r in rules if r["port"] == 9443)
        self.assertEqual(r_9443["destinations"][0]["type"], "haproxy")
        self.assertEqual(r_9443["destinations"][0]["target"], "2001:db8::1")

    def test_parse_nftables_json(self):
        rules = parse_nftables_json(SAMPLE_NFTABLES_JSON)
        self.assertEqual(len(rules), 2)
