    def test_target_sanitization_rejects_injections(self):
        from core.nftables_parser import _build_xforwarder_rule_from_nftables
        # Malicious targets with command injection attempts must be rejected
        self.assertIsNone(_build_xforwarder_rule_from_nftables(80, "10.0.0.1; rm -rf /", 80))
        self.assertIsNone(_build_xforwarder_rule_from_nftables(80, "10.0.0.1 && cat /etc/passwd", 80))
        self.assertIsNone(_build_xforwarder_rule_from_nftables(80, "10.0.0.1 | bash", 80))
        self.assertIsNone(_build_xforwarder_rule_from_nftables(80, "10.0.0.1`reboot`", 80))

        # Valid targets must be accepted
        r_ipv4 = _build_xforwarder_rule_from_nftables(80, "10.88.1.2", 80)
        self.assertIsNotNone(r_ipv4)
        self.assertEqual(r_ipv4["destinations"][1]["target"], "10.88.1.2")

        r_ipv6 = _build_xforwarder_rule_from_nftables(443, "[2001:db8::1]", 443)
        self.assertIsNotNone(r_ipv6)
        self.assertEqual(r_ipv6["destinations"][0]["target"], "2001:db8::1")

