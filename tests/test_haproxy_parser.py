#!/usr/bin/env python3
"""
Unit tests for HAProxy Configuration Parser & Importer.
Standard Library unittest only.
"""

import os
import sys
import unittest
import tempfile
import json

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from unittest.mock import patch
from core.config_manager import validate_rule
from core.haproxy_parser import (
    parse_haproxy_content,
    parse_haproxy_file,
    discover_importable_rules,
    import_haproxy_rules_into_config,
    find_candidate_haproxy_files,
    archive_legacy_haproxy_files
)


SAMPLE_HAPROXY_CONFIG = """
global
    daemon
    maxconn 256

defaults
    mode tcp
    timeout connect 5000ms
    timeout client 50000ms
    timeout server 50000ms

# Listen block with IPv6 target and send-proxy
listen relay_2083
    bind *:2083
    mode tcp
    server srv_2083 [2001:4ba0:cafe:84e::1]:2083 send-proxy-v2

# Listen block with IPv4 target
listen relay_8080
    bind 0.0.0.0:8080
    server srv_8080 1.2.3.4:8080 check

# Listen block with multiple binds
listen relay_8443
    bind :::8443
    bind *:8443
    server srv_8443 10.0.0.5:8443

# Frontend and backend separation
frontend fe_443
    bind *:443
    mode tcp
    default_backend be_443

backend be_443
    mode tcp
    server srv_443 [2600:1f18::5]:443 send-proxy-v2

# Another frontend with use_backend
frontend fe_80
    bind *:80
    use_backend be_80

backend be_80
    server srv_80 192.168.1.100:80

# Sixth port
listen custom_9090
    bind *:9090
    server foreign 5.6.7.8:9090
"""


class TestHAProxyParser(unittest.TestCase):

    def test_parse_sample_haproxy_content(self):
        rules = parse_haproxy_content(SAMPLE_HAPROXY_CONFIG)
        self.assertEqual(len(rules), 6)

        ports = {r["port"] for r in rules}
        self.assertEqual(ports, {80, 443, 2083, 8080, 8443, 9090})

        # Verify IPv6 target
        rule_2083 = next(r for r in rules if r["port"] == 2083)
        self.assertEqual(rule_2083["destinations"][0]["target"], "2001:4ba0:cafe:84e::1")
        self.assertEqual(rule_2083["destinations"][0]["port"], 2083)
        self.assertEqual(rule_2083["destinations"][0]["type"], "haproxy")
        self.assertTrue(rule_2083["destinations"][0].get("proxy_protocol"))

        rule_8080 = next(r for r in rules if r["port"] == 8080)
        self.assertFalse(rule_8080["destinations"][0].get("proxy_protocol"))

        # Verify frontend/backend resolution
        rule_443 = next(r for r in rules if r["port"] == 443)
        self.assertEqual(rule_443["destinations"][0]["target"], "2600:1f18::5")
        self.assertEqual(rule_443["destinations"][0]["port"], 443)

        rule_80 = next(r for r in rules if r["port"] == 80)
        self.assertEqual(rule_80["destinations"][0]["target"], "192.168.1.100")

    def test_import_into_config_file(self):
        with tempfile.NamedTemporaryFile(mode="w", suffix=".json", delete=False) as cfg_file:
            json.dump({
                "schema_version": 2,
                "wan_interface": "auto",
                "rules": [
                    {"id": "rule-443", "port": 443, "destinations": []}  # Already configured
                ]
            }, cfg_file)
            cfg_path = cfg_file.name

        with tempfile.NamedTemporaryFile(mode="w", suffix=".cfg", delete=False) as haproxy_file:
            haproxy_file.write(SAMPLE_HAPROXY_CONFIG)
            haproxy_path = haproxy_file.name

        try:
            # Parse specific file
            parsed_rules = parse_haproxy_file(haproxy_path)
            self.assertEqual(len(parsed_rules), 6)

            # Discover importable (port 443 should be skipped since already configured)
            existing = [{"port": 443}]
            importable = [r for r in parsed_rules if r["port"] not in {443}]
            self.assertEqual(len(importable), 5)

        finally:
            if os.path.exists(cfg_path):
                os.remove(cfg_path)
            if os.path.exists(haproxy_path):
                os.remove(haproxy_path)

    def test_no_placeholder_ip_and_takeover_prevents_rediscovery(self):
        """Verifies no fake 10.88.1.2 backup is injected, range/protected overlap holds, and XForwarder configs/baks are ignored."""
        rules = parse_haproxy_content(SAMPLE_HAPROXY_CONFIG)
        for r in rules:
            self.assertEqual(len(r["destinations"]), 1)
            self.assertNotEqual(r["destinations"][0]["target"], "10.88.1.2")
            ok, err = validate_rule(dict(r))
            self.assertTrue(ok, f"HAProxy imported rule :{r.get('port')} failed validation: {err}")

        with tempfile.TemporaryDirectory() as tmpdir:
            managed_cfg = os.path.join(tmpdir, "haproxy.cfg")
            bak_cfg = os.path.join(tmpdir, "haproxy.cfg.bak.2026")
            with open(managed_cfg, "w", encoding="utf-8") as f:
                f.write("# Generated by XForwarder\nfrontend fwd_8080\n    bind *:8080\n")
            with open(bak_cfg, "w", encoding="utf-8") as f:
                f.write(SAMPLE_HAPROXY_CONFIG)

            # XForwarder-generated files must never be parsed as unmanaged rules
            self.assertEqual(parse_haproxy_file(managed_cfg), [])

            # Respects port ranges, excluded_ports, and protected_ports
            with patch("core.haproxy_parser.find_candidate_haproxy_files", return_value=[bak_cfg]):
                existing = [
                    {"port": 8000, "port_range": "8000-8500", "destinations": [{"priority": 1, "type": "nftables", "target": "10.0.0.1", "port": 8000}]}
                ]
                disc = discover_importable_rules(existing_rules=existing, protected_ports={22, 80})
                disc_ports = {r["port"] for r in disc}
                # 8080 & 8443 fall inside 8000-8500; 80 is protected
                self.assertEqual(disc_ports, {443, 2083, 9090})


if __name__ == "__main__":
    unittest.main()
